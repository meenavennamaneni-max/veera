#!/usr/bin/env node
/**
 * Populate the D1 message index for Dev's Personal AI.
 *
 * Explicitly retrieves accessible messages through the Discord REST API with
 * pagination and rate-limit handling, then writes D1 SQL for the `messages`
 * index. The Worker also lazily indexes messages it retrieves during
 * searches; this script is the explicit bulk population / refresh process.
 *
 * Usage:
 *   node scripts/index-messages.js                        # uses DISCORD_GUILD_ID
 *   node scripts/index-messages.js --guild 123 --max-per-channel 300
 *   node scripts/index-messages.js --out d1-index.sql --prune
 *
 * Then apply the SQL:
 *   npx wrangler d1 execute devs-personal-ai --remote --file d1-index.sql
 *
 * Prerequisites:
 *   - Run `npx wrangler d1 migrations apply devs-personal-ai --remote` first
 *     so the `messages` table exists.
 *   - The bot must be in the guild with View Channels and Read Message History.
 *
 * Deleted-message status: Discord's bot REST API has no delete events without
 * the Gateway, so deletions are not streamed to the index. Run with --prune
 * to drop previously indexed rows for each scanned channel and replace them
 * with what currently exists.
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadScriptEnv, REPO_ROOT } from './lib.js';
import { createDiscordClient } from '../src/discord.js';
import {
  isSearchableTextChannel,
  messageCreatedAt,
} from '../src/search.js';

/** SQL string literal (single quotes escaped). */
function sqlString(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`;
}

async function main() {
  const env = loadScriptEnv();
  const token = env.DISCORD_BOT_TOKEN;
  const guildId = env.guild || env.DISCORD_GUILD_ID;
  const maxPerChannel = Number(env['max-per-channel'] || env.MAX_PER_CHANNEL || 200);
  const outPath = resolve(REPO_ROOT, env.out || 'd1-index.sql');
  const prune = env.prune === 'true';

  if (!token) {
    throw new Error('DISCORD_BOT_TOKEN is required (set it in .dev.vars or the environment).');
  }
  if (!guildId) {
    throw new Error('Provide the guild to index: --guild <id> or DISCORD_GUILD_ID.');
  }
  if (!Number.isInteger(maxPerChannel) || maxPerChannel < 1 || maxPerChannel > 5000) {
    throw new Error('--max-per-channel must be an integer between 1 and 5000.');
  }

  const client = createDiscordClient({ token });
  console.log(`Fetching channels for guild ${guildId} ...`);
  const channels = (await client.getGuildChannels(guildId)).filter(isSearchableTextChannel);
  console.log(`Found ${channels.length} searchable text/announcement channels.`);

  const lines = [
    '-- Generated by scripts/index-messages.js for Dev\'s Personal AI',
    `-- guild ${guildId} · ${new Date().toISOString()}`,
    'BEGIN;',
    `CREATE TABLE IF NOT EXISTS messages (
  message_id TEXT PRIMARY KEY,
  guild_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  channel_name TEXT NOT NULL DEFAULT '',
  author_id TEXT NOT NULL DEFAULT '',
  author_name TEXT NOT NULL DEFAULT '',
  content TEXT NOT NULL DEFAULT '',
  created_at INTEGER NOT NULL,
  indexed_at INTEGER NOT NULL
);`,
    'CREATE INDEX IF NOT EXISTS idx_messages_guild_created ON messages(guild_id, created_at DESC);',
    'CREATE INDEX IF NOT EXISTS idx_messages_channel ON messages(channel_id);',
  ];

  const now = Math.floor(Date.now() / 1000);
  let totalMessages = 0;
  let skippedChannels = 0;

  for (const channel of channels) {
    const { messages, skipped } = await client.listMessagesPaginated(channel.id, {
      maxMessages: maxPerChannel,
    });
    if (skipped) {
      skippedChannels += 1;
      console.log(`  #${channel.name}: skipped (missing access or deleted).`);
      continue;
    }

    if (prune) {
      lines.push(`DELETE FROM messages WHERE channel_id = ${sqlString(channel.id)};`);
    }

    for (const message of messages) {
      if (!message.id) continue;
      const createdAt = messageCreatedAt(message);
      const authorName = message.author?.global_name || message.author?.username || 'unknown';
      lines.push(
        `INSERT INTO messages (message_id, guild_id, channel_id, channel_name, author_id, author_name, content, created_at, indexed_at) VALUES (` +
          `${sqlString(message.id)}, ${sqlString(guildId)}, ${sqlString(channel.id)}, ${sqlString(channel.name)}, ` +
          `${sqlString(message.author?.id)}, ${sqlString(authorName)}, ${sqlString(message.content || '')}, ` +
          `${createdAt}, ${now}) ON CONFLICT(message_id) DO UPDATE SET channel_name = excluded.channel_name, ` +
          `author_name = excluded.author_name, content = excluded.content, indexed_at = excluded.indexed_at;`,
      );
      totalMessages += 1;
    }
    console.log(`  #${channel.name}: indexed ${messages.length} messages.`);
  }

  lines.push('COMMIT;');
  writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');

  console.log('\nSummary:');
  console.log(`  Channels scanned: ${channels.length} (skipped ${skippedChannels})`);
  console.log(`  Messages written: ${totalMessages}`);
  console.log(`  SQL file: ${outPath}`);
  console.log('\nNext steps:');
  console.log('  1. npx wrangler d1 migrations apply devs-personal-ai --remote');
  console.log(`  2. npx wrangler d1 execute devs-personal-ai --remote --file ${outPath}`);
  console.log('Re-run this script periodically to refresh the index.');
}

main().catch((error) => {
  console.error(`index-messages failed: ${error.message}`);
  process.exitCode = 1;
});
